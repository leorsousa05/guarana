import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';
import test from 'node:test';

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const render = (element) => renderToStaticMarkup(element);

test('Skills registry keeps accessible scopes, generated counts, findability, and Markdown reading', async (t) => {
  const vite = await createServer({
    root: webRoot,
    server: { middlewareMode: true },
    appType: 'custom',
    optimizeDeps: { noDiscovery: true, include: [] },
  });
  t.after(() => vite.close());

  const { Skills, SkillsRegistry, filterSkills } = await vite.ssrLoadModule('/src/components/Skills.jsx');
  const { handleTabKeyDown } = await vite.ssrLoadModule('/src/components/common.jsx');
  const globalSkill = {
    name: 'review-release-candidate',
    description: 'Inspect a release candidate before publishing.',
    scope: 'global',
    content: '# Release review\n\nPreserve **the exact Markdown** source.',
  };
  const projectSkill = {
    name: 'workspace-build-check',
    description: 'Run this workspace build and inspect failures.',
    scope: 'project',
    content: '# Build check\n\nRun the project build.',
  };
  const response = {
    data: {
      global: [globalSkill, { ...globalSkill, name: 'release-notes-audit', description: 'Capture decisions made in release notes.' }],
      project: [projectSkill],
    },
    error: null,
  };

  const initial = render(React.createElement(Skills));
  assert.match(initial, /aria-label="Skills"/);
  assert.match(initial, /role="tablist" aria-label="Skill scope"/);
  assert.match(initial, /role="tab"[^>]*id="skills-tab-global"[^>]*aria-controls="skills-panel-global"[^>]*aria-selected="true"/);
  assert.match(initial, /role="tab"[^>]*id="skills-tab-project"[^>]*aria-controls="skills-panel-project"[^>]*aria-selected="false"/);
  assert.match(initial, /role="status">Loading global skills/);
  assert.match(initial, /id="skills-panel-global"[^>]*role="tabpanel"/);
  assert.match(initial, /id="skills-panel-project"[^>]*role="tabpanel"/);
  assert.doesNotMatch(initial, /Global \(\d+\)|Project \(\d+\)/);

  const registry = render(React.createElement(SkillsRegistry, {
    response,
    scope: 'global',
    onScopeChange() {},
    onRead() {},
  }));
  assert.match(registry, />Global \(2\)<\/button>/);
  assert.match(registry, />Project \(1\)<\/button>/);
  assert.match(registry, /Global scope/);
  assert.match(registry, /Generated by Guarana · Available across projects\./);
  assert.match(registry, /review-release-candidate/);
  assert.match(registry, /Inspect a release candidate before publishing\./);
  assert.match(registry, /type="search"[^>]*placeholder="Name or description"/);
  assert.match(registry, /Showing 2 of 2/);
  assert.doesNotMatch(registry, /\/home\/|file:\/\/|SKILL\.md/);

  assert.deepEqual(filterSkills(response.data.global, 'RELEASE'), response.data.global);
  assert.deepEqual(filterSkills(response.data.global, 'publishing'), [globalSkill]);
  assert.deepEqual(filterSkills(response.data.global, 'absent'), []);

  const projectView = render(React.createElement(SkillsRegistry, {
    response,
    scope: 'project',
    onScopeChange() {},
    onRead() {},
  }));
  assert.match(projectView, /Project scope/);
  assert.match(projectView, /Generated by Guarana · Generated for this project\./);
  assert.match(projectView, /workspace-build-check/);

  const emptyView = render(React.createElement(SkillsRegistry, {
    response: { data: { global: [], project: [] }, error: null },
    scope: 'global',
  }));
  assert.match(emptyView, /No generated Global skills yet/);
  assert.match(emptyView, /No generated Project skills yet/);
  assert.match(emptyView, />Global \(0\)<\/button>/);
  assert.match(emptyView, />Project \(0\)<\/button>/);

  for (const failedResponse of [
    { data: null, error: 'network failure' },
    { data: { error: 'skill loading failed', global: [], project: [] }, error: null },
  ]) {
    const failedView = render(React.createElement(SkillsRegistry, {
      response: failedResponse,
      scope: 'global',
    }));
    assert.match(failedView, /role="alert">Unable to load Global skills/);
    assert.doesNotMatch(failedView, /Global \(\d+\)|Project \(\d+\)/);
    assert.doesNotMatch(failedView, /role="status">Loading/);
  }

  const reader = render(React.createElement(SkillsRegistry, {
    response,
    scope: 'global',
    reading: globalSkill,
  }));
  assert.match(reader, /role="dialog"[^>]*aria-labelledby="specs-modal-title"/);
  assert.match(reader, /<h1>Release review<\/h1>/);
  assert.match(reader, /Preserve <strong>the exact Markdown<\/strong> source\./);

  const keyboard = (key, current) => {
    let selected;
    let focused;
    let prevented = false;
    handleTabKeyDown({
      key,
      target: { closest: () => ({ dataset: { tabId: current } }) },
      currentTarget: { querySelector: (selector) => ({ focus: () => { focused = selector; } }) },
      preventDefault: () => { prevented = true; },
    }, ['global', 'project'], (next) => { selected = next; });
    assert.equal(prevented, true);
    assert.equal(selected, focused.includes('project') ? 'project' : 'global');
    return selected;
  };
  assert.equal(keyboard('ArrowLeft', 'global'), 'project');
  assert.equal(keyboard('ArrowRight', 'project'), 'global');
  assert.equal(keyboard('Home', 'project'), 'global');
  assert.equal(keyboard('End', 'global'), 'project');

  const css = fs.readFileSync(path.join(webRoot, 'src/style.css'), 'utf8');
  assert.match(css, /\.skills-page,\s*\.skills-page \* \{ min-width: 0; \}/);
  assert.match(css, /@media \(max-width: 540px\)[\s\S]*?\.skills-page \.skill-entry\s*\{\s*grid-template-columns: minmax\(0, 1fr\) auto/s);
  assert.match(css, /@media \(prefers-reduced-motion: reduce\)[\s\S]*?\.skills-page, \.skills-page \*/);
});
