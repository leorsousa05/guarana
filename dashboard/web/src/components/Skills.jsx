import { useState } from 'react';
import { usePoll } from '../hooks/usePoll.js';
import { EmptyState, ErrorBanner, handleTabKeyDown } from './common.jsx';
import { SpecsMarkdownModal } from './SpecsMarkdownModal.jsx';

const TABS = [
  ['global', 'Global'],
  ['project', 'Project'],
];

const SCOPE_CONTEXT = {
  global: 'Available across projects.',
  project: 'Generated for this project.',
};

function successfulSkillsData(response) {
  const data = response?.data;
  if (
    response?.error ||
    !data ||
    data.error ||
    !Array.isArray(data.global) ||
    !Array.isArray(data.project)
  ) return null;
  return data;
}

export function filterSkills(skills, query) {
  const term = query.trim().toLowerCase();
  if (!term) return skills;
  return skills.filter((skill) => `${skill.name}\n${skill.description}`.toLowerCase().includes(term));
}

export function SkillScopeTabs({ response, scope, onScopeChange }) {
  const skillsByScope = successfulSkillsData(response);

  return (
    <div
      className="skills-tabs"
      role="tablist"
      aria-label="Skill scope"
      onKeyDown={(event) => handleTabKeyDown(event, TABS.map(([id]) => id), onScopeChange)}
    >
      {TABS.map(([id, label]) => {
        const count = skillsByScope ? ` (${skillsByScope[id].length})` : '';

        return (
          <button
            key={id}
            type="button"
            role="tab"
            id={`skills-tab-${id}`}
            data-tab-id={id}
            aria-controls={`skills-panel-${id}`}
            aria-selected={scope === id}
            tabIndex={scope === id ? 0 : -1}
            className={scope === id ? 'skills-tab skills-tab--on' : 'skills-tab'}
            onClick={() => onScopeChange(id)}
          >
            {label}{count}
          </button>
        );
      })}
    </div>
  );
}

function ScopePanel({ response, data, scope, active, search, onSearch, onRead }) {
  const [, label] = TABS.find(([id]) => id === scope);
  const skills = data?.[scope] || [];
  const visibleSkills = filterSkills(skills, search);
  const error = response.error
    || response.data?.error
    || (response.data && !data ? 'Invalid skills data.' : null);

  return (
    <div
      id={`skills-panel-${scope}`}
      role="tabpanel"
      aria-labelledby={`skills-tab-${scope}`}
      tabIndex={0}
      hidden={!active}
      className="skills-panel"
    >
      <header className="skills-panel-head">
        <div>
          <p className="skills-kicker">{label} scope</p>
          <p className="skills-panel-context">Generated by Guarana · {SCOPE_CONTEXT[scope]}</p>
        </div>
        {data && <span className="skills-total">{skills.length} generated</span>}
      </header>

      {error ? <ErrorBanner text={`Unable to load ${label} skills: ${error}`} /> : null}
      {!error && !data && (
        <p className="loading" role="status">Loading {label.toLowerCase()} skills…</p>
      )}
      {!error && data && skills.length === 0 && (
        <EmptyState copy={`No generated ${label} skills yet. Reusable procedures will appear here when Guarana creates them.`} />
      )}

      {!error && data && skills.length > 0 && (
        <>
          {active && (
            <div className="skills-search">
              <label htmlFor={`skills-search-${scope}`}>Find a skill</label>
              <input
                id={`skills-search-${scope}`}
                type="search"
                value={search}
                onChange={(event) => onSearch(event.target.value)}
                placeholder="Name or description"
              />
              <p className="skills-search-count" aria-live="polite">
                Showing {visibleSkills.length} of {skills.length}
              </p>
            </div>
          )}

          {visibleSkills.length > 0 ? (
            <ul className="skill-list" aria-label={`${label} generated skills`}>
              {visibleSkills.map((skill) => (
                <li key={`${skill.scope || scope}:${skill.name}`}>
                  <button
                    type="button"
                    className="skill-entry"
                    onClick={() => onRead(skill)}
                  >
                    <span className="skill-entry-name">{skill.name}</span>
                    <span className="skill-entry-description">{skill.description}</span>
                    <span className="skill-entry-action">Read</span>
                  </button>
                </li>
              ))}
            </ul>
          ) : (
            <p className="skills-no-match" role="status">No skills match “{search}”.</p>
          )}
        </>
      )}
    </div>
  );
}

export function SkillsRegistry({
  response,
  scope = 'global',
  onScopeChange = () => {},
  reading = null,
  onRead = () => {},
  onClose = () => {},
}) {
  const [search, setSearch] = useState('');
  const data = successfulSkillsData(response);
  const changeScope = (nextScope) => {
    setSearch('');
    onScopeChange(nextScope);
  };

  return (
    <section id="skills" className="skills-page" aria-label="Skills">
      <header className="skills-page-head">
        <div>
          <p className="skills-kicker">Generated skill library</p>
          <h2 className="section-title">Skills</h2>
        </div>
        <p className="skills-intro">
          Reusable procedures created by Guarana. Global skills are available across projects; Project skills belong to this workspace.
        </p>
      </header>

      <SkillScopeTabs response={response} scope={scope} onScopeChange={changeScope} />

      <div className="skills-panels">
        {TABS.map(([id]) => (
          <ScopePanel
            key={id}
            response={response}
            data={data}
            scope={id}
            active={scope === id}
            search={search}
            onSearch={setSearch}
            onRead={onRead}
          />
        ))}
      </div>

      {reading && (
        <SpecsMarkdownModal
          title={reading.name}
          text={reading.content}
          onClose={onClose}
        />
      )}
    </section>
  );
}

export function Skills() {
  const response = usePoll('/api/skills', 5000);
  const [scope, setScope] = useState('global');
  const [reading, setReading] = useState(null);

  return (
    <SkillsRegistry
      response={response}
      scope={scope}
      onScopeChange={setScope}
      reading={reading}
      onRead={setReading}
      onClose={() => setReading(null)}
    />
  );
}
